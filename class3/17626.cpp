#include <iostream>

using namespace std;

int dp[50001];

int main(void) {
  int n;
  cin >> n;
  /*
    dp[1] = 1^2 = 1 : 1
    dp[2] = 1^2 + 1^2 = 2 : 2
    dp[3] = 1^2 + 1^2 + 1^2 = 3 : 3
    dp[4] = 2^2 = 4 : 1
    dp[5] = 2^2 + 1^1 = 5 : 2
    dp[6] = 4 + 1 + 1 = 7 : 3
    dp[7] = 4 + 1 + 1 + 1 = 7 : 4
    dp[8] = 2^2 + 2^2 = 8 : 2
    dp[9] = 3^2 = 9 : 1
    dp[10] = 3^2 + 1^2 = 10 : 2
    dp[11] = 3^2 + 1 + 1 = 11 : 3
    dp[12] = 9 + 1 + 1 + 1 = 12 : 4
    dp[13] = 9 + 4 = 13 : 2
    dp[14] = 9 + 4 + 1 = 14 : 3
    dp[15] = 9 + 4 + 1 + 1 = 15 : 4
    dp[16] = 16 : 1
    dp[17] = 16 + 1 : 2
    dp[18] = 16 + 1 + 1 : 3
    dp[19] = 16 + 1 + 1 + 1 : 4
    dp[20] = 16 + 4 : 2
    dp[21] = 16 + 4 + 1 : 3
    dp[22] = 9 + 9 + 4 : 3
    dp[23] = 9 + 9 + 4 + 1 : 4
  */
  dp[0] = 0;
  for (int i = 1; i <= n; i++) {
    dp[i] = i;
    for (int j = 1; j * j <= i; j++) {
      dp[i] = min(dp[i], dp[i - j * j] + 1);
    }
  }

  cout << dp[n] << "\n";
}